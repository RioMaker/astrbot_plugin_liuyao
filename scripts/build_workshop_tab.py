"""Bundle the shared workshop for the management page's separately signed asset root."""

from pathlib import Path

PAGES = Path(__file__).resolve().parents[1] / "pages"
TARGET = PAGES / "manage" / "workshop-tab.js"


def render_bundle() -> str:
    source = PAGES / "optimize"
    html = (source / "index.html").read_text(encoding="utf-8")
    _, start, rest = html.partition("<main>")
    content, end, _ = rest.partition("</main>")
    if not start or not end:
        raise ValueError("Workshop page must contain one <main> element")
    css = (source / "style.css").read_text(encoding="utf-8").rstrip()
    template = f"<style>\n{css}\n</style>\n{content.strip()}"
    literal = template.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
    controller = (source / "controller.js").read_text(encoding="utf-8")
    return (
        "// Generated by scripts/build_workshop_tab.py from pages/optimize.\n"
        "export function mountWorkshop(host, bridge) {\n"
        '  const root = host.attachShadow({ mode: "open" });\n'
        f"  root.innerHTML = `{literal}`;\n"
        "  startWorkshop(root, bridge);\n"
        "}\n\n"
        + controller
    )


if __name__ == "__main__":
    TARGET.write_text(render_bundle(), encoding="utf-8", newline="\n")
